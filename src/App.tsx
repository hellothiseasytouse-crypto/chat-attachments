import React, { useCallback, useRef, useState } from "react";
import { Activity, AlertTriangle, FlaskConical, ShieldCheck, WifiOff } from "lucide-react";
import WorkbenchConsole, { type ConsoleRunOptions } from "./WorkbenchConsole";

type Message = {
  role: "user" | "assistant";
  text: string;
  model?: string;
};

const MODELS = [
  { name: "NOXEN Core 1.0", label: "Core", description: "General-purpose response profile · simulated" },
  { name: "NOXEN Core 1.5", label: "Nova", description: "Research and coding profile · simulated" },
  { name: "NOXEN Swift", label: "Swift", description: "Fast response profile · simulated" },
  { name: "NOXEN Studio", label: "Studio", description: "Creative and advanced-work profile · simulated" },
  { name: "NOXEN Studio Plus", label: "Studio Plus", description: "Extended advanced-work profile · simulated" }
];

function chooseDemoModel(prompt: string): string {
  const value = prompt.toLowerCase();
  if (/\b(architecture|deep research|audit|complex|strategy|roadmap|comprehensive)\b/.test(value)) return "NOXEN Studio";
  if (/\b(code|coding|debug|typescript|javascript|python|sql|react|api|function|component|build|github)\b/.test(value)) return "NOXEN Core 1.5";
  if (/\b(story|write|draft|rewrite|brainstorm|design|creative|script|poem)\b/.test(value)) return "NOXEN Studio";
  if (/\b(quick|briefly|simple|define|translate|calculate)\b/.test(value)) return "NOXEN Swift";
  return "NOXEN Core 1.0";
}

function makeDemoOutput(prompt: string, model: string, tool?: string): string {
  const profile = tool && tool !== "none" ? tool : "standard";
  const toolNote = profile === "standard"
    ? "Standard response path"
    : "Requested tool profile: **" + profile + "** (simulated only)";
  return [
    "## Playground response",
    "",
    "> This is a local simulator response, not an answer generated by a NOXEN AI model.",
    "",
    "**Input received**",
    "",
    "```text",
    prompt,
    "```",
    "",
    "**Runtime details**",
    "",
    "- Model target: **" + model.replace(/^NOXEN\s+/i, "") + "**",
    "- Dispatch: " + toolNote,
    "- Execution: local demo adapter",
    "- Network/API calls: none",
    "",
    "**What this test confirms**",
    "",
    "The console accepted the input, dispatched it through the playground adapter, and displayed a model-labelled response. This validates the interface flow only; it does not measure model intelligence or actual tool execution.",
    "",
    "To test another path, try `/help`, `/models`, `/status`, `/bench Explain how a browser request works`, or `/export`."
  ].join("\n");
}

export default function App() {
  const [messages, setMessages] = useState<Message[]>([]);
  const [selectedModel, setSelectedModel] = useState(MODELS[0].name);
  const [autoModelRouting, setAutoModelRouting] = useState(true);
  const [running, setRunning] = useState(false);
  const [activity, setActivity] = useState<string | null>(null);
  const runToken = useRef(0);

  const run = useCallback(async (prompt: string, options?: ConsoleRunOptions) => {
    const token = ++runToken.current;
    const model = options?.modelOverride || (autoModelRouting ? chooseDemoModel(prompt) : selectedModel);
    setMessages(previous => [...previous, { role: "user", text: prompt }]);
    setRunning(true);
    setActivity("LOCAL SIMULATOR · preparing mock response");
    await new Promise(resolve => window.setTimeout(resolve, 650));
    if (token !== runToken.current) return;
    setMessages(previous => [
      ...previous,
      { role: "assistant", text: makeDemoOutput(prompt, model, options?.toolOverride), model }
    ]);
    setActivity(null);
    setRunning(false);
  }, [autoModelRouting, selectedModel]);

  const stop = useCallback(() => {
    runToken.current += 1;
    setActivity(null);
    setRunning(false);
  }, []);

  const clear = useCallback(() => {
    runToken.current += 1;
    setMessages([]);
    setActivity(null);
    setRunning(false);
  }, []);

  return (
    <main className="playground">
      <header className="playground-header">
        <a className="brand" href="/" aria-label="NOXEN Console Test Lab home">
          <span className="brand-icon"><FlaskConical size={18} /></span>
          <span>NOXEN <b>CONSOLE</b></span>
        </a>
        <span className="top-pill"><span className="pulse-dot" /> TEST LAB</span>
      </header>

      <section className="playground-intro">
        <div className="intro-copy">
          <div className="eyebrow"><Activity size={14} /> STANDALONE PLAYGROUND</div>
          <h1>Test the console.<br /><span>Not the live models.</span></h1>
          <p>This separate site lets you explore the terminal interface and its command flows without changing the NOXEN production app.</p>
        </div>
        <div className="runtime-card">
          <div className="runtime-card-title"><WifiOff size={15} /> BACKEND STATUS</div>
          <strong>NOT CONNECTED</strong>
          <small>Local simulator · no AI inference</small>
        </div>
      </section>

      <section className="notice" role="note">
        <AlertTriangle size={17} />
        <div>
          <strong>Demo mode only</strong>
          <p>Responses are generated locally by this test page. It does not call NOXEN Core, Nova, Studio, Studio Plus, external search, image generation, or any NOXEN API. Model names and tool profiles are selectable examples.</p>
        </div>
      </section>

      <WorkbenchConsole
        messages={messages}
        models={MODELS}
        selectedModel={selectedModel}
        autoModelRouting={autoModelRouting}
        isOnline={false}
        running={running}
        activity={activity}
        onModelChange={setSelectedModel}
        onAutoModelRoutingChange={setAutoModelRouting}
        onRun={run}
        onStop={stop}
        onClear={clear}
      />

      <footer className="playground-footer">
        <span><ShieldCheck size={13} /> Isolated test harness · no production data access</span>
        <span>Built for NOXEN Console UI testing</span>
      </footer>
    </main>
  );
}
